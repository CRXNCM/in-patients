export function requestSummary(names = []) {
  const labels = names.map((name) => String(name || '').trim()).filter(Boolean)
  if (!labels.length) return 'Service request'
  if (labels.length <= 3) return labels.join(', ')
  return `${labels.slice(0, 3).join(', ')} +${labels.length - 3} more`
}

const DONE = new Set(['approved', 'fulfilled', 'completed'])
const REJECTED = new Set(['rejected', 'cancelled', 'not_supplied'])

function groupStatus(services) {
  if (!services.length) return 'pending'
  if (services.every((line) => DONE.has(line.lineStatus))) return 'approved'
  if (services.every((line) => REJECTED.has(line.lineStatus))) return 'rejected'
  if (services.some((line) => DONE.has(line.lineStatus) || REJECTED.has(line.lineStatus))) return 'partly_approved'
  return 'pending'
}

function isEmptySource(record) {
  const services = record.services || []
  const returns = record.returnItems || []
  return (record.status === 'logged' || record.recordRole === 'source') && !services.length && !returns.length
}

export function historyGroupKey(record) {
  if (!record || record.autoGenerated || record.type === 'pharmacy_return') return null
  if (record.submissionId) return `sub:${record.submissionId}`
  const billingKey = String(record.billingKey || '')
  const split = billingKey.match(/^reception:([^:]+):/)
  if (split) return `split:${split[1]}`
  const department = billingKey.match(/^(pharmacy|laboratory):([^:]+):/)
  if (department) return `order:${department[2]}`
  if (record.workflowOrderId) return `order:${record.workflowOrderId}`
  return null
}

export function groupReceptionHistory(records = []) {
  const loose = []
  const buckets = new Map()

  for (const record of records) {
    if (isEmptySource(record)) continue
    const key = historyGroupKey(record)
    const lines = record.services || []
    if (!key || record.type === 'pharmacy_return' || record.autoGenerated) {
      loose.push({ sort: record.recordedAt || '', record })
      continue
    }
    if (!lines.length && !(record.returnItems || []).length) {
      loose.push({ sort: record.recordedAt || '', record })
      continue
    }
    if (!buckets.has(key)) buckets.set(key, [])
    buckets.get(key).push(record)
  }

  const grouped = [...buckets.entries()].map(([key, members]) => {
    if (members.length === 1 && !members[0].groupedRequest && !members[0].workflowKind && members[0].type === 'daily_services') {
      return { sort: members[0].recordedAt || '', record: members[0] }
    }
    const ordered = [...members].sort((a, b) => String(a.recordedAt || '').localeCompare(String(b.recordedAt || '')))
    const nurseRecord = ordered.find((record) => !record.workflowKind && record.type === 'daily_services') || ordered[0]
    const services = ordered.flatMap((record) => (record.services || []).map((service, index) => ({
      ...service,
      id: `${record.id}-${service.id || index}`,
      lineStatus: service.lineStatus || record.status,
    })))
    const latest = ordered[ordered.length - 1]
    const submissionId = ordered.find((record) => record.submissionId)?.submissionId || key
    return {
      sort: latest?.recordedAt || nurseRecord?.recordedAt || '',
      record: {
        id: `request-${key}`,
        submissionId,
        groupedRequest: true,
        recordName: requestSummary(services.map((line) => line.serviceName)),
        type: 'daily_services',
        recordDate: nurseRecord?.recordDate,
        recordedAt: nurseRecord?.recordedAt,
        recordedBy: nurseRecord?.recordedBy,
        status: groupStatus(services),
        services,
        source: 'nurse',
        auditTrail: ordered.flatMap((record) => record.auditTrail || []),
      },
    }
  })

  return [...loose, ...grouped]
    .sort((a, b) => String(b.sort).localeCompare(String(a.sort)))
    .map((entry) => entry.record)
}
