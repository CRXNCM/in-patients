import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { groupReceptionHistory } from './receptionHistory.js'

describe('reception request history grouping', () => {
  it('shows one group for a nurse request and marks the group partly approved', () => {
    const rows = groupReceptionHistory([
      {
        id: 'bill-a',
        submissionId: 'SR-001',
        type: 'daily_services',
        status: 'approved',
        recordName: 'Patient A',
        recordedAt: '2026-10-25T09:00:00.000Z',
        recordedBy: 'Pharmacist',
        workflowKind: 'pharmacy',
        services: [{ id: 'a', category: 'Pharmacy', serviceName: 'Medicine A', quantity: 1, total: 10 }],
      },
      {
        id: 'bill-b',
        submissionId: 'SR-001',
        type: 'daily_services',
        status: 'pending',
        recordName: 'Patient A',
        recordedAt: '2026-10-25T06:15:00.000Z',
        recordedBy: 'Nurse A',
        services: [{ id: 'c', category: 'Nursing', serviceName: 'Dressing', quantity: 1, total: 15 }],
      },
      {
        id: 'other',
        type: 'daily_services',
        status: 'approved',
        recordName: 'Room charge',
        recordedAt: '2026-10-25T08:00:00.000Z',
        recordedBy: 'System',
        autoGenerated: true,
        services: [{ id: 'room', serviceName: 'Room', quantity: 1, total: 100 }],
      },
    ])

    const group = rows.find((row) => row.submissionId === 'SR-001')
    assert.ok(group)
    assert.equal(rows.filter((row) => row.submissionId === 'SR-001').length, 1)
    assert.equal(group.status, 'partly_approved')
    assert.equal(group.recordedBy, 'Nurse A')
    assert.equal(group.recordName, 'Dressing, Medicine A')
    assert.deepEqual(group.services.map((line) => [line.serviceName, line.lineStatus]), [
      ['Dressing', 'pending'],
      ['Medicine A', 'approved'],
    ])
    assert.equal(rows.some((row) => row.recordName === 'Room charge'), true)
  })
})
