import { medicineSummary } from '@/services/pharmacyFulfillment'
import { groupReceptionHistory } from '@/lib/receptionHistory'

function receptionNote(status) {
  if (status === 'approved') return 'Reception approved'
  if (status === 'pending') return 'Waiting for reception'
  if (status === 'rejected') return 'Reception rejected'
  return 'With the department'
}

function auditFrom(history = []) {
  return history.map((entry) => ({
    action: entry.action,
    by: entry.by,
    at: entry.at,
    note: entry.note || entry.reasonNote || '',
  }))
}

export function pharmacyOrderRecord(order) {
  return {
    id: `pharmacy-order-${order.id}`,
    patientId: order.patientId,
    recordName: 'Pharmacy request',
    type: 'pharmacy_request',
    status: order.status || 'pending',
    source: 'pharmacy',
    subjectType: 'mother',
    autoGenerated: false,
    recordDate: String(order.requestedAt || '').slice(0, 10),
    recordedAt: order.requestedAt,
    recordedBy: order.requestedByName || 'Nurse',
    submissionId: order.submissionId || '',
    services: medicineSummary(order).map((item) => ({
      id: item.lineId,
      category: 'Pharmacy',
      serviceName: item.name,
      quantity: item.requestedQuantity,
      total: 0,
      lineStatus: item.status,
      notes: [
        Number(item.suppliedQuantity) > 0 ? `Handed over ${item.suppliedQuantity}` : '',
        Number(item.returned) > 0 ? `Returned ${item.returned}` : '',
        receptionNote(item.receptionStatus),
      ].filter(Boolean).join(' · '),
    })),
    auditTrail: auditFrom(order.history),
    workflowOrderId: order.id,
  }
}

export function laboratoryOrderRecord(order) {
  return {
    id: `laboratory-order-${order.id}`,
    patientId: order.patientId,
    recordName: 'Laboratory request',
    type: 'laboratory_request',
    status: order.status || 'pending',
    source: 'laboratory',
    subjectType: 'mother',
    autoGenerated: false,
    recordDate: String(order.requestedAt || '').slice(0, 10),
    recordedAt: order.requestedAt,
    recordedBy: order.requestedByName || 'Nurse',
    submissionId: order.submissionId || '',
    services: (order.items || []).map((item) => ({
      id: item.lineId,
      category: 'Laboratory',
      serviceName: item.name,
      quantity: item.quantity,
      total: 0,
      lineStatus: item.status,
      notes: [
        item.priority === 'urgent' ? 'Urgent' : '',
        item.reason || '',
        receptionNote(item.receptionStatus),
      ].filter(Boolean).join(' · '),
    })),
    auditTrail: auditFrom(order.history),
    workflowOrderId: order.id,
  }
}

export function recordsWithWardRequests(records, pharmacyOrders, laboratoryOrders, patientId) {
  const pharmacy = pharmacyOrders.filter((order) => order.patientId === patientId).map(pharmacyOrderRecord)
  const laboratory = laboratoryOrders.filter((order) => order.patientId === patientId).map(laboratoryOrderRecord)
  const covered = new Set([...pharmacy, ...laboratory].map((record) => record.workflowOrderId))
  const chart = records.filter((record) => {
    const kind = record.workflowKind
    if ((kind === 'pharmacy' || kind === 'laboratory') && covered.has(record.workflowOrderId)) return false
    return true
  })
  return groupReceptionHistory([...chart, ...pharmacy, ...laboratory])
}
